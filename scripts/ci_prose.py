"""Check this repository's own pull request text and commit messages with readcost.

    python scripts/ci_prose.py --base BASE_SHA --head HEAD_SHA

Run by .github/workflows/prose.yml on every pull request (opened, edited,
pushed to) and on every push to main. It checks:

- each commit message in BASE..HEAD, merges left out, as `--format commit`;
- the pull request title and description, read from GITHUB_EVENT_PATH;
- AI attribution in those commits, in that text and in the lines the change
  adds: session links, co-author trailers, "generated by" or "generated
  with" lines, and an Anthropic no-reply address as author or committer.

Findings print as GitHub warnings and as a table in the step summary. The
exit status is 1 when attribution is found, or when a commit message reaches
--commits-fail-on (default block; no commit message on main reached it in
the 80 before this check). The pull request text is advisory by default
(--pr-fail-on never): at readcost's precision, gating a description would
fail good pull requests.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from readcost import Analyzer, load_config  # noqa: E402
from readcost.prtext import check_pull_request, read_event  # noqa: E402
from readcost.report import _gh_data, _gh_property  # noqa: E402

VERDICT_RANK = {"never": 99, "pass": 0, "advise": 1, "block": 2}
ZERO = "0" * 40

ATTRIBUTION = re.compile(
    r"claude\.ai/code/session_"
    r"|^\s*claude-session\s*:"
    r"|^\s*co-authored-by\s*:[^\n]*(claude|anthropic)"
    r"|generated (by|with) \[?claude"
    r"|noreply@anthropic\.com",
    re.IGNORECASE | re.MULTILINE)

# Files that name these patterns on purpose: this script and its test, and the
# evaluation fetcher that searches GitHub for pull requests that carry them.
ATTRIBUTION_EXEMPT = ("scripts/ci_prose.py", "tests/test_ci_prose.py",
                      "scripts/strip_attribution.py", "tests/test_strip_attribution.py",
                      "scripts/fetch_ai_text.py", "tests/test_broad_fetchers.py")


REPO = ROOT  # the repository to read; --repo changes it, for tests


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, check=True).stdout


def has_commit(sha: str) -> bool:
    return bool(sha) and sha != ZERO and subprocess.run(
        ["git", "cat-file", "-e", f"{sha}^{{commit}}"], cwd=REPO, capture_output=True).returncode == 0


def commits(base: str, head: str) -> list[str]:
    """Non-merge commits in base..head, oldest first; only head when base is unknown."""
    if has_commit(base):
        out = git("rev-list", "--no-merges", "--reverse", f"{base}..{head}")
    else:
        out = git("rev-list", "--no-merges", "-n", "1", head)
    return out.split()


def added_lines(base: str, head: str) -> list[tuple[str, str]]:
    """(path, line) for each line the change adds, outside ATTRIBUTION_EXEMPT."""
    if has_commit(base):
        spec = [f"{base}...{head}"]
    elif has_commit(f"{head}^"):
        spec = [f"{head}^", head]
    else:
        return []
    out = git("diff", "--no-color", "--unified=0", *spec, "--", ".",
              *[f":(exclude){p}" for p in ATTRIBUTION_EXEMPT])
    lines, path = [], ""
    for line in out.splitlines():
        if line.startswith("+++ "):
            path = line[6:] if line.startswith("+++ b/") else ""
        elif line.startswith("+") and path:
            lines.append((path, line[1:]))
    return lines


def pull_request(event_path: str | None) -> dict | None:
    """The pull request from the event, with its current title and description.

    The event holds the text as it was when the run started. A rerun after an
    edit by the repository token (strip-attribution), which starts no run of
    its own, must see the edited text, so the live copy is read when a token
    is available.
    """
    if not event_path or not Path(event_path).is_file():
        return None
    pr = read_event(event_path)
    token, repo = os.environ.get("GH_TOKEN"), os.environ.get("GITHUB_REPOSITORY")
    if pr and token and repo:
        import urllib.request

        req = urllib.request.Request(f"https://api.github.com/repos/{repo}/pulls/{pr['number']}",
                                     headers={"Authorization": f"Bearer {token}",
                                              "Accept": "application/vnd.github+json"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                live = json.loads(resp.read())
            pr = {**pr, "title": live.get("title"), "body": live.get("body")}
        except OSError as exc:
            print(f"::warning::could not read the live pull request text ({exc}); using the event's copy")
    return pr


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--base", default="")
    ap.add_argument("--head", default="HEAD")
    ap.add_argument("--event", default=os.environ.get("GITHUB_EVENT_PATH"))
    ap.add_argument("--commits-fail-on", choices=("never", "advise", "block"), default="block")
    ap.add_argument("--pr-fail-on", choices=("never", "advise", "block"), default="never")
    ap.add_argument("--repo", default=str(ROOT))
    args = ap.parse_args(argv)
    global REPO
    REPO = Path(args.repo)

    analyzer = Analyzer(load_config())
    attribution: list[str] = []
    rows: list[tuple[str, str, str, str]] = []  # (where, verdict, cost index, findings)
    failed = False

    def report(where: str, result, fail_on: str) -> None:
        nonlocal failed
        for f in result.findings:
            print(f"::warning title={_gh_property(f'readcost {f.feature}: {where}')}::"
                  f"{_gh_data(f'{f.message}. {f.suggestion}')}")
        listed = "; ".join(f"{f.feature}: {f.excerpt or f.message}" for f in result.findings) or "none"
        rows.append((where, result.verdict, f"{result.cost_index:.1f}", listed))
        if VERDICT_RANK[result.verdict] >= VERDICT_RANK[fail_on]:
            failed = True
            print(f"::error title={_gh_property(f'readcost: {where}')}::"
                  f"{_gh_data(f'{result.verdict} (cost index {result.cost_index:.1f})')}")

    for sha in commits(args.base, args.head):
        short = sha[:7]
        message = git("log", "-1", "--format=%B", sha)
        who = git("log", "-1", "--format=%an <%ae>%n%cn <%ce>", sha)
        if ATTRIBUTION.search(message):
            attribution.append(f"commit {short}: AI attribution in the message")
        if ATTRIBUTION.search(who) or any(line.split(" <")[0] == "Claude" for line in who.splitlines()):
            attribution.append(f"commit {short}: AI author or committer ({who.strip().replace(chr(10), '; ')})")
        report(f"commit {short}", analyzer.check_text(message, "commit", f"commit {short}"), args.commits_fail_on)

    pr = pull_request(args.event)
    if pr is not None:
        title, body = pr.get("title") or "", pr.get("body") or ""
        if ATTRIBUTION.search(title) or ATTRIBUTION.search(body):
            attribution.append("pull request: AI attribution in the title or description")
        # The same checks as `readcost check --pr-text`, without its minimum length.
        title_result, body_result = check_pull_request(analyzer, pr)
        report("pull request title", title_result, args.pr_fail_on)
        report("pull request description", body_result, args.pr_fail_on)

    for path, line in added_lines(args.base, args.head):
        if ATTRIBUTION.search(line):
            attribution.append(f"{path}: AI attribution in an added line")

    for a in attribution:
        print(f"::error title=AI attribution::{_gh_data(a)}")

    summary = ["## readcost on this change", "",
               "| Checked | Verdict | Cost index | Findings |", "| --- | --- | --- | --- |"]
    summary += [f"| {w} | {v} | {c} | {f.replace('|', '/')} |" for w, v, c, f in rows]
    summary += ["", "Pull request text is advisory: many findings are wrong (README, Limits).", ""]
    summary += (["### AI attribution", ""] + [f"- {a}" for a in attribution]) if attribution else []
    text = "\n".join(summary) + "\n"
    dest = os.environ.get("GITHUB_STEP_SUMMARY")
    if dest:
        with open(dest, "a", encoding="utf-8") as fh:
            fh.write(text)
    else:
        print(text)
    return 1 if attribution or failed else 0


if __name__ == "__main__":
    sys.exit(main())
