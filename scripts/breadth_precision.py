def _parts(path: str) -> list[str]:
    return path.lower().split("/")


def _skipped_dir(path: str, extra: set[str] = frozenset()) -> bool:
    return any(p in SKIP_DIRS or p in extra for p in _parts(path)[:-1])


def _skip_name(path: str) -> bool:
    return _parts(path)[-1].startswith(SKIP_NAMES)


def eligible(stratum: str, path: str) -> bool:
    """Whether a tree path may be chosen for a stratum (the README is chosen apart)."""
    p = path.lower()
    if _skipped_dir(path):
        return False
    if stratum == "md":
        return p.endswith(MD_EXT) and not _skip_name(path) and (
            p.startswith(MD_PREFIX) or any(x in "/" + p for x in MD_INFIX))
    if stratum == "rst":
        return p.endswith(".rst") and not _skip_name(path) and p.startswith(RST_PREFIX)
    if stratum == "html":
        return p.endswith((".html", ".htm")) and not _skip_name(path) and p.startswith(HTML_PREFIX)
    if stratum in SRC_STRATA:
        name = _parts(path)[-1]
        if _skipped_dir(path, SRC_SKIP_DIRS):
            return False
        if name.endswith((".min.js", "_pb2.py", ".pb.go")) or ".generated." in name or "_generated." in name:
            return False
        return p.endswith(SRC_STRATA[stratum])
    raise ValueError(stratum)


def readme_stratum(path: str) -> str | None:
    p = path.lower()
    if p.endswith(MD_EXT):
        return "md"
    if p.endswith(".rst"):
        return "rst"
    return None


def choose(items: list, k: int, seed: str) -> list:
    """Sort, shuffle with seed, take the first k."""
    order = sorted(items)
    random.Random(seed).shuffle(order)
    return order[:k]


def is_bot(name: str, email: str) -> bool:
    s = f"{name} {email}".lower()
    return any(b in s for b in BOT)


def parse_log(out: str) -> list[dict]:
    """Records of `git log --format=%H%x00%an%x00%ae%x00%aI%x00%B%x1e`."""
    recs = []
    for chunk in out.split("\x1e"):
        chunk = chunk.lstrip("\n")
        if not chunk:
            continue
        sha, name, email, date, body = chunk.split("\x00", 4)
        recs.append({"sha": sha, "name": name, "email": email, "date": date, "message": body.rstrip("\n") + "\n"})
    return recs


def eligible_commits(recs: list[dict], since: str = SINCE) -> list[dict]:
    t0 = datetime.fromisoformat(since + "T00:00:00+00:00")
    return [r for r in recs if not is_bot(r["name"], r["email"]) and datetime.fromisoformat(r["date"]) >= t0]


def eligible_prs(items: list[dict]) -> list[dict]:
    out = []
    for it in items:
        user = it.get("user") or {}
        login = user.get("login") or ""
        if not (it.get("body") or "").strip() or user.get("type") == "Bot" or login.endswith("[bot]"):
            continue
        out.append(it)
    return out


def walk(cands: list[dict], excluded: set[str], per_lang: int = PER_LANG, owner_cap: int = OWNER_CAP,
         langs: tuple[str, ...] = LANGS) -> tuple[list[dict], Counter]:
    """The registered walk: per language in order, shuffled; skip excluded, forks, archived, full owners."""
    owners: Counter = Counter()
    picked, drops = [], Counter()
    for lang in langs:
        pool = sorted((c for c in cands if c["language"] == lang), key=lambda c: c["repo"].lower())
        random.Random(f"{SEED}:walk:{lang}").shuffle(pool)
        n = 0
        for c in pool:
            if n >= per_lang:
                break
            owner = c["repo"].split("/")[0].lower()
            why = hp.excluded(c["repo"], excluded) or ("fork" if c["fork"] else None) \
                or ("archived" if c["archived"] else None) or ("owner cap" if owners[owner] >= owner_cap else None)
            if why:
                drops[why] += 1
                continue
            owners[owner] += 1
            picked.append(c)
            n += 1
    return picked, drops


@contextlib.contextmanager
def loosened(rule: str):
    """Set the rule's threshold constants in readcost.features one step looser, for one run."""
    from readcost import features
    old = {k: getattr(features, k) for k in LOOSE[rule]}
    try:
        for k, v in LOOSE[rule].items():
            setattr(features, k, v)
        yield
    finally:
        for k, v in old.items():
            setattr(features, k, v)


def near_misses(default: list[dict], loose: list[dict], rule: str) -> list[dict]:
    """Findings of rule in the looser run whose sentence holds no default finding of rule."""
    spans = [(f["start"], f["end"]) for f in default if f["rule"] == rule]
    out = []
    for f in loose:
        if f["rule"] != rule:
            continue
        lo, hi = f["sentence_start"], f["sentence_end"]
        if any(lo <= a < hi or lo < b <= hi for a, b in spans):
            continue
        out.append(f)
    return out


def dedupe_against(items: list[dict], others: list[dict]) -> list[dict]:
    """Drop items whose rule and sentence equal one of others'."""
    seen = {(o["rule"], o["sentence"]) for o in others}
    return [it for it in items if (it["rule"], it["sentence"]) not in seen]


