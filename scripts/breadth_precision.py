def search_range(lang: str, lo: int, hi: int, log: list) -> list[dict]:
    """Every repository of one query, splitting the star range while it is over the search limit."""
    q = lang_query(lang, lo, hi)
    items, page = [], 1
    while True:
        wait = hp.SEARCH_GAP - (time.time() - hp._last_search)
        if wait > 0:
            time.sleep(wait)
        hp._last_search = time.time()
        res = json.loads(hp.gh(["-X", "GET", "search/repositories", "-f", f"q={q}", "-f", "sort=stars",
                                "-f", "order=desc", "-f", "per_page=100", "-f", f"page={page}"]))
        log.append({"q": q, "page": page, "total_count": res["total_count"],
                    "incomplete": res.get("incomplete_results"), "at": datetime.now(UTC).isoformat()})
        if page == 1 and res["total_count"] > SEARCH_LIMIT and lo < hi:
            return [x for a, b in split_range(lo, hi) for x in search_range(lang, a, b, log)]
        items += [it | {"__q": q} for it in res["items"]]
        if len(res["items"]) < 100 or len(items) >= min(res["total_count"], SEARCH_LIMIT):
            return items
        page += 1


CAND_FIELDS = ("repo", "language", "stars", "created_at", "default_branch", "fork", "archived")
# The query of each page is in eval/breadth/search-log.json.


def write_candidates(path: Path, rows: list[dict]) -> None:
    lines = ["\t".join(CAND_FIELDS)]
    for r in sorted(rows, key=lambda r: (r["language"], r["repo"].lower())):
        lines.append("\t".join(str(r[k]).lower() if isinstance(r[k], bool) else str(r[k]) for k in CAND_FIELDS))
    path.write_text("\n".join(lines) + "\n")


def read_candidates(path: Path) -> list[dict]:
    lines = path.read_text().splitlines()
    head = lines[0].split("\t")
    out = []
    for line in lines[1:]:
        r = dict(zip(head, line.split("\t")))
        r["stars"] = int(r["stars"])
        r["fork"], r["archived"] = r["fork"] == "true", r["archived"] == "true"
        out.append(r)
    return out


def cmd_search(args) -> None:
    log: list = []
    seen: dict[str, dict] = {}
    for lang in LANGS:
        got = search_range(lang, *STARS, log)
        for it in got:
            seen.setdefault(it["full_name"], {
                "repo": it["full_name"], "language": lang, "stars": it["stargazers_count"],
                "created_at": it["created_at"], "default_branch": it["default_branch"], "fork": it["fork"],
                "archived": it["archived"], "query": it["__q"]})
        print(f"{lang}: {len(got)}", flush=True)
    out = ROOT / "eval/breadth/candidates.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    write_candidates(out, list(seen.values()))
    (args.ref / "search-log.json").write_text(json.dumps(log, indent=1))
    print(len(seen), "candidates ->", out)


