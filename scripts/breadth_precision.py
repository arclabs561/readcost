def check_path(stratum: str, path: str) -> str:
    """The path readcost sees, for its format: commit messages as .gitmessage, PR bodies as .md."""
    if stratum == "commit":
        return path.split("/", 1)[1] + ".gitmessage"
    if stratum == "pr":
        return path.replace("/", "-") + ".md"
    return path


def _findings(res, repo, commit, path, rules=RULES) -> list[dict]:
    out = []
    for f in res.findings:
        if f.feature not in rules or f.start is None:
            continue
        out.append({"rule": f.feature, "message": f.message, "excerpt": f.excerpt, "sentence": f.sentence,
                    "start": f.start, "end": f.end, "sentence_start": f.sentence_start,
                    "sentence_end": f.sentence_end,
                    "key": hp.finding_key(repo, commit, path, f.feature, f.start, f.end)})
    return out


def check_text(an, text: str, rec: dict) -> dict:
    """Default run, one looser run per threshold rule, and the sentences free of any finding."""
    from readcost.extract import extract
    from readcost.features import Context, show

    stratum, repo, commit, path = rec["stratum"], rec["repo"], rec["commit"], rec["path"]
    cpath = check_path(stratum, path)
    nlp = an.nlp
    cache = ParseCache(nlp)
    an._nlp = cache
    try:
        res = an.check_text(text, None, cpath, lines=ALL_LINES)
        out = rec | {"words": res.words}
        if any("not English" in n for n in res.notes):
            return out | {"drop": "not English"}
        if res.words < MIN_WORDS[stratum]:
            return out | {"drop": f"under {MIN_WORDS[stratum]} words"}
        if stratum == "md" and hp.fenced_share(text) > 0.5:
            return out | {"drop": "mostly code"}
        findings = _findings(res, repo, commit, path)
        taken = [(f.sentence_start, f.sentence_end) for f in res.findings if f.sentence_start is not None]
        near = {}
        for rule in LOOSE:
            with loosened(rule):
                lres = an.check_text(text, None, cpath, lines=ALL_LINES)
            taken += [(f.sentence_start, f.sentence_end) for f in lres.findings if f.sentence_start is not None]
            lf = _findings(lres, repo, commit, path, (rule,))
            for f in lf:
                f["key"] = hp.finding_key(repo, commit, path, f"near-{rule}", f["start"], f["end"])
            near[rule] = near_misses(findings, lf, rule)
        sentences = []
        ctx = Context(an.cfg, an.profile, an.allow, set())
        for seg in extract(text, cpath, None, comments=an.cfg.comments):
            doc = cache(seg.text)
            ctx.codes = seg.codes
            for sent in doc.sents:
                words = [t for t in sent if t.is_alpha]
                if len(words) < 4 or not any(t.pos_ in ("VERB", "AUX") for t in sent):
                    continue
                whole = seg.span(sent.start_char, sent.end_char)
                if not whole or any(a < whole[1] and whole[0] < b for a, b in taken):
                    continue
                sentences.append({"start": whole[0], "end": whole[1], "words": len(words),
                                  "sentence": show(ctx, doc, sent.start, sent.end - 1)})
        return out | {"findings": findings, "near": [f for r in LOOSE for f in near[r]], "sentences": sentences}
    finally:
        an._nlp = nlp


def sentence_tokens(an, text: str, rec: dict, start: int, end: int) -> list | None:
    """(text, pos, is_alpha, start, end) per token of the sentence at these offsets, parsed again."""
    from readcost.extract import extract
    for seg in extract(text, check_path(rec["stratum"], rec["path"]), None, comments=an.cfg.comments):
        doc = an.nlp(seg.text)
        for sent in doc.sents:
            if seg.span(sent.start_char, sent.end_char) == (start, end):
                return [[t.text, t.pos_, t.is_alpha, *(seg.span(t.idx, t.idx + len(t.text)) or (None, None))]
                        for t in sent]
    return None


_AN = None


def _worker(job):
    global _AN
    from readcost.engine import read_source
    if _AN is None:
        _AN = analyzer()
    rec, local = job
    text, _ = read_source(local)
    try:
        return check_text(_AN, text, rec)
    except Exception as exc:  # noqa: BLE001 -- one bad file must not stop the run; recorded as a drop
        return rec | {"drop": "check error", "error": repr(exc)[:300]}


def texts(ref: Path) -> list[tuple[dict, str]]:
    """(record, local path) of every text of every kept repository, duplicates marked, in sorted order."""
    state = json.loads((ref / "fetch-state.json").read_text())
    repos = json.loads((ref / "repos.json").read_text())
    prs = json.loads((ref / "prs.json").read_text()) if (ref / "prs.json").exists() else {}
    rows = []
    for repo, st in sorted(state.items(), key=lambda kv: kv[0].lower()):
        if repo == "_walk" or not repos.get(repo, {}).get("kept"):
            continue
        for f in st["files"] + prs.get(repo, {}).get("files", []):
            if f["stratum"] not in STRATA:
                continue
            rec = {"stratum": f["stratum"], "repo": repo, "commit": st["commit"], "path": f["path"],
                   "blob": f["blob"]}
            if not f.get("local"):
                rows.append((rec | {"drop": "too large"}, ""))
                continue
            rows.append((rec, str(ref / f["local"])))
    seen: set[tuple[str, str]] = set()
    out = []
    for rec, local in sorted(rows, key=lambda x: (x[0]["stratum"], x[0]["repo"].lower(), x[0]["path"])):
        if local:
            digest = hashlib.sha256(Path(local).read_bytes()).hexdigest()
            rec["sha256"] = digest
            if (rec["stratum"], digest) in seen:
                rec["drop"] = "duplicate text"
            seen.add((rec["stratum"], digest))
        out.append((rec, local))
    return out


def cmd_readmes(args) -> None:
    frozen_check()
    from readcost.engine import read_source
    state = json.loads((args.ref / "fetch-state.json").read_text())
    an = analyzer()
    repos = {}
    for repo, st in sorted(state.items()):
        if repo == "_walk":
            continue
        if st.get("drop"):
            repos[repo] = {"kept": False, "drop": st["drop"]}
            continue
        readme = next((f for f in st["files"] if f.get("readme")), None)
        if readme is None:
            repos[repo] = {"kept": False, "drop": "no README"}
            continue
        if not readme.get("local"):
            repos[repo] = {"kept": False, "drop": "README over 1 MB"}
            continue
        text, _ = read_source(str(args.ref / readme["local"]))
        res = an.check_text(text, None, readme["path"], lines=ALL_LINES)
        if any("not English" in n for n in res.notes):
            repos[repo] = {"kept": False, "drop": "README not English"}
        elif res.words < README_MIN_WORDS:
            repos[repo] = {"kept": False, "drop": f"README under {README_MIN_WORDS} words"}
        else:
            repos[repo] = {"kept": True}
        repos[repo]["readme_words"] = res.words
    (args.ref / "repos.json").write_text(json.dumps(repos, indent=1))
    print(Counter(v.get("drop", "kept") for v in repos.values()))


def cmd_prs(args) -> None:
    repos = json.loads((args.ref / "repos.json").read_text())
    path = args.ref / "prs.json"
    out = json.loads(path.read_text()) if path.exists() else {}
    for n, repo in enumerate(sorted(r for r, v in repos.items() if v["kept"]), 1):
        if repo in out:
            continue
        wait = hp.SEARCH_GAP - (time.time() - hp._last_search)
        if wait > 0:
            time.sleep(wait)
        hp._last_search = time.time()
        try:
            res = json.loads(hp.gh(["-X", "GET", "search/issues", "-f", f"q=repo:{repo} is:pr created:>={SINCE}",
                                    "-f", "sort=created", "-f", "order=desc", "-f", "per_page=100"], tries=2))
        except (RuntimeError, FileNotFoundError) as exc:
            out[repo] = {"drop": "search error", "error": str(exc)[:200], "files": []}
            continue
        items = {it["number"]: it for it in eligible_prs(res["items"])}
        files = []
        for num in choose(list(items), FILES_PER_REPO["pr"], f"{SEED}:pr:{repo}"):
            body = items[num]["body"].replace("\r\n", "\n")
            data = body.encode()
            files.append({"stratum": "pr", "path": f"pr/{num}", "blob": hashlib.sha256(data).hexdigest(),
                          "bytes": len(data), "created_at": items[num]["created_at"],
                          "local": _store(args.ref, repo, f"prs/{num}.md", data)})
        out[repo] = {"total_count": res["total_count"], "eligible": len(items), "files": files}
        if n % 25 == 0:
            path.write_text(json.dumps(out))
            print(f"{n} repositories", flush=True)
    path.write_text(json.dumps(out))
    print(sum(len(v["files"]) for v in out.values()), "pull request bodies")


def cmd_check(args) -> None:
    frozen_check()
    import readcost
    jobs = texts(args.ref)
    rows = [rec for rec, _ in jobs if rec.get("drop")]
    todo = [(rec, local) for rec, local in jobs if not rec.get("drop")]
    t0 = time.time()
    with ProcessPoolExecutor(args.workers) as ex:
        for n, row in enumerate(ex.map(_worker, todo, chunksize=4), 1):
            rows.append(row)
            if n % 200 == 0:
                print(f"{n}/{len(todo)} texts in {time.time() - t0:.0f}s", flush=True)
    rows.sort(key=lambda r: (r["stratum"], r["repo"].lower(), r["path"]))
    meta = {"readcost": readcost.__version__,
            "features_sha256": hashlib.sha256((ROOT / "src/readcost/features.py").read_bytes()).hexdigest()}
    (args.ref / "check-meta.json").write_text(json.dumps(meta))
    (args.ref / "checked.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
    print(Counter((r["stratum"], r.get("drop", "kept")) for r in rows))


