class ParseCache(hp._CachingNLP):
    """Parses each text once, for the default run and every looser run."""

    def pipe(self, texts):
        texts = list(texts)
        missing = list(dict.fromkeys(t for t in texts if t not in self.docs))
        for t, doc in zip(missing, self.nlp.pipe(missing)):
            self.docs[t] = doc
        for t in texts:
            yield self.docs[t]


