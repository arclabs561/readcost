def _store(ref: Path, repo: str, path: str, data: bytes) -> str:
    local = ref / "files" / repo / path
    local.parent.mkdir(parents=True, exist_ok=True)
    local.write_bytes(data)
    return str(local.relative_to(ref))


def fetch_repo(ref: Path, repo: str, branch: str) -> dict:
    work = ref / "git" / repo.replace("/", "__")
    shutil.rmtree(work, ignore_errors=True)
    work.parent.mkdir(parents=True, exist_ok=True)
    url = f"https://github.com/{repo}.git"
    base = ["clone", "--quiet", "--bare", "--filter=blob:none", "--single-branch", "--branch", branch]
    try:
        st: dict = {}
        try:
            hp.git([*base, f"--shallow-since={SINCE}", url, str(work)], timeout=600)
            st["clone"] = "shallow-since"
        except RuntimeError:
            shutil.rmtree(work, ignore_errors=True)
            hp.git([*base, "--depth", "1", url, str(work)], timeout=600)
            st["clone"] = "depth 1"
        st["commit"] = hp.git(["rev-parse", "HEAD"], cwd=work).strip()
        tree = {}
        for line in hp.git(["ls-tree", "-r", "-z", "HEAD"], cwd=work).split("\0"):
            if not line:
                continue
            meta, path = line.split("\t", 1)
            mode, kind, sha = meta.split()
            if kind == "blob" and not mode.startswith("12"):
                tree[path] = sha

        def read(path):
            return hp.git(["cat-file", "blob", tree[path]], cwd=work, binary=True)

        files = []
        readme = hp.pick_readme(list(tree))
        st["readme"] = readme
        if readme is not None:
            data = read(readme)
            rec = {"stratum": readme_stratum(readme) or "readme-other", "path": readme, "blob": tree[readme],
                   "bytes": len(data), "readme": True}
            if len(data) <= MAX_BYTES:
                rec["local"] = _store(ref, repo, readme, data)
            files.append(rec)
        for stratum in ("md", "rst", "html", *SRC_STRATA):
            cands = [p for p in tree if eligible(stratum, p) and p != readme]
            order = choose(cands, len(cands), f"{SEED}:{stratum}:{repo}")
            taken, reads = 0, 0
            for path in order:
                if taken >= FILES_PER_REPO[stratum] or reads >= 10:
                    break
                data = read(path)
                reads += 1
                if stratum == "html" and GENERATOR.search(data[:4096]):
                    continue
                taken += 1
                rec = {"stratum": stratum, "path": path, "blob": tree[path], "bytes": len(data)}
                limit = MAX_SRC_BYTES if stratum in SRC_STRATA else MAX_BYTES
                if len(data) <= limit:
                    rec["local"] = _store(ref, repo, path, data)
                files.append(rec)
        log = hp.git(["log", "--no-merges", "--format=%H%x00%an%x00%ae%x00%aI%x00%B%x1e", "HEAD"], cwd=work)
        recs = eligible_commits(parse_log(log))
        st["commits_eligible"] = len(recs)
        by_sha = {r["sha"]: r for r in recs}
        for sha in choose(list(by_sha), FILES_PER_REPO["commit"], f"{SEED}:commit:{repo}"):
            data = by_sha[sha]["message"].encode()
            rec = {"stratum": "commit", "path": f"commit/{sha}", "blob": sha, "bytes": len(data),
                   "date": by_sha[sha]["date"]}
            rec["local"] = _store(ref, repo, f"commits/{sha}.gitmessage", data)
            files.append(rec)
        st["files"] = files
        return st
    finally:
        shutil.rmtree(work, ignore_errors=True)


def cmd_fetch(args) -> None:
    cands = read_candidates(ROOT / "eval/breadth/candidates.tsv")
    picked, drops = walk(cands, excluded_repos())
    state_path = args.ref / "fetch-state.json"
    state = json.loads(state_path.read_text()) if state_path.exists() else {}
    state["_walk"] = {"picked": [c["repo"] for c in picked], "drops": dict(drops)}
    todo = [c for c in picked if c["repo"] not in state]

    def one(c):
        try:
            st = fetch_repo(args.ref, c["repo"], c["default_branch"])
        except (RuntimeError, subprocess.TimeoutExpired) as exc:
            st = {"drop": "fetch error", "error": str(exc)[:300]}
        state[c["repo"]] = st | {"language": c["language"], "stars": c["stars"]}
        return c

    with ThreadPoolExecutor(args.workers) as ex:
        for n, _ in enumerate(ex.map(one, todo), 1):
            if n % 25 == 0:
                state_path.write_text(json.dumps(state))
                print(f"{n}/{len(todo)} repositories", flush=True)
    state_path.write_text(json.dumps(state))
    print("walk drops", dict(drops), "fetched", Counter(v.get("drop", "ok") for k, v in state.items() if k != "_walk"))


