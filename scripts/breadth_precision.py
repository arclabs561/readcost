def draw_stratum(stratum: str, kept: list[dict], tokens_for) -> tuple[list[dict], dict]:
    """Findings per rule, near misses per threshold rule, then random decoys, for one stratum.

    kept: checked records of the stratum. tokens_for(rec, start, end) gives a
    sentence's tokens for a decoy span, or None.
    """
    q = quota(stratum)
    counts: dict = {}
    base = lambda c: {"repo": c["repo"], "commit": c["commit"], "path": c["path"], "blob": c["blob"],
                      "stratum": stratum}
    allf = [f | base(c) for c in kept for f in c["findings"]]
    alln = [f | base(c) for c in kept for f in c["near"]]
    deduped = hp.dedupe(allf)
    near = hp.dedupe(dedupe_against(alln, allf))
    counts["findings"] = dict(Counter(f["rule"] for f in allf))
    counts["deduped"] = dict(Counter(f["rule"] for f in deduped))
    counts["near"] = dict(Counter(f["rule"] for f in alln))
    counts["near_deduped"] = dict(Counter(f["rule"] for f in near))
    out = []
    sampled, sampled_near = {}, {}
    for rule in RULES:
        k = q["default" if rule in DEFAULT_RULES else "opt-in"]
        got = hp.draw([f for f in deduped if f["rule"] == rule], k, PER_REPO_CAP, f"{SEED}:{stratum}:{rule}")
        sampled[rule] = len(got)
        out += [f | {"item": "finding"} for f in got]
        if rule in LOOSE:
            k = q["near-default" if rule in DEFAULT_RULES else "near-opt-in"]
            got = hp.draw([f for f in near if f["rule"] == rule], k, PER_REPO_CAP,
                          f"{SEED}:{stratum}:near-{rule}")
            sampled_near[rule] = len(got)
            out += [f | {"item": "near"} for f in got]
    counts["sampled"], counts["sampled_near"] = sampled, sampled_near
    # random decoys
    sents = []
    for c in kept:
        for s in c["sentences"]:
            sents.append(s | base(c) | {"rule": "", "rec": c,
                                        "key": hp.finding_key(c["repo"], c["commit"], c["path"], "sentence",
                                                              s["start"], s["end"])})
    pool = hp.dedupe(sents)
    counts["decoy_pool"] = len(pool)
    names = hp.rule_names(q["decoy"], f"{SEED}:{stratum}:decoy-rules")
    order = sorted(pool, key=lambda x: x["key"])
    random.Random(f"{SEED}:{stratum}:decoy-random").shuffle(order)
    per_repo: Counter = Counter()
    decoys = []
    for s in order:
        if len(decoys) >= q["decoy"]:
            break
        if per_repo[s["repo"]] >= DECOY_REPO_CAP:
            continue
        toks = tokens_for(s["rec"], s["start"], s["end"])
        if not toks:
            continue
        span = hp.decoy_span([(t[0], t[1], t[2]) for t in toks], random.Random(f"{SEED}:span:{s['key']}"))
        if span is None:
            continue
        run = toks[span[0]:span[1] + 1]
        if run[0][3] is None or run[-1][4] is None:
            continue
        per_repo[s["repo"]] += 1
        rule = names[len(decoys)]
        start, end = run[0][3], run[-1][4]
        decoys.append(base(s) | {
            "rule": rule, "message": hp.decoy_message(rule, [t[0] for t in run]), "excerpt": None,
            "sentence": s["sentence"], "start": start, "end": end, "sentence_start": s["start"],
            "sentence_end": s["end"], "item": "decoy",
            "key": hp.finding_key(s["repo"], s["commit"], s["path"], "decoy-random", start, end)})
    counts["decoys"] = len(decoys)
    return out + decoys, counts


def build_sample(checked: list[dict], sources: dict[tuple, str], tokens_for) -> tuple[list[dict], dict]:
    counts: dict = {}
    sample = []
    for stratum in STRATA:
        kept = [c for c in checked if c["stratum"] == stratum and not c.get("drop")]
        items, counts[stratum] = draw_stratum(stratum, kept, tokens_for)
        sample += items
    ids = hp.assign_ids([it["key"] for it in sample], seed=f"{SEED}:ids")
    for it in sample:
        src = sources[(it["repo"], it["path"])]
        it["i"] = ids[it["key"]]
        it["family"] = FAMILY[it["stratum"]]
        it["kind"] = kind_of(it["stratum"], it["path"])
        if it["excerpt"] is None:  # a decoy shows the source's own words
            it["excerpt"] = src[it["start"]:it["end"]]
        it["before"], it["after"] = hp.context(src, it["sentence_start"], it["sentence_end"])
    return sorted(sample, key=lambda x: x["key"]), counts


