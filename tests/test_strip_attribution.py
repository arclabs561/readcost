"""scripts/strip_attribution.py: which lines go, which stay."""

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINK = "https://claude.ai/code/" + "session_01ABC"
FOOT = "_Generated by [" + "Claude Code](https://claude.ai/code)_"


def _mod():
    spec = importlib.util.spec_from_file_location("strip_attribution", ROOT / "scripts" / "strip_attribution.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_footer_and_separator_are_removed():
    assert _mod().strip(f"Fixes the cache.\n\n---\n{FOOT}\n") == "Fixes the cache.\n"


def test_footer_with_a_session_link_and_a_bare_link_are_removed():
    m = _mod()
    body = f"Fixes the cache.\n\n{LINK}\n\n---\n_Generated by [Claude Code]({LINK})_"
    assert m.strip(body) == "Fixes the cache.\n"


def test_robot_line_and_session_trailer_are_removed():
    body = "Summary.\n\n\U0001f916 Generated with [" + "Claude Code](https://claude.com/claude-code)\n\nClaude-Session: " + LINK
    assert _mod().strip(body) == "Summary.\n"


def test_clean_text_and_mentions_in_prose_are_left_alone():
    m = _mod()
    assert m.strip("Fixes the cache.\n") is None
    assert m.strip(None) is None
    prose = "The footer reads Generated by Claude Code in some tools, and we strip it.\n---\nMore."
    assert m.strip(prose) is None


class FakeGitHub:
    def __init__(self, prs, reviews):
        self.prs, self.reviews, self.calls = prs, reviews, []

    def call(self, method, path, data=None):
        self.calls.append((method, path, data))

    def pages(self, path):
        if path.startswith("pulls?"):
            return iter(self.prs)
        return iter(self.reviews.get(int(path.split("/")[1]), []))


def test_sweep_edits_only_what_needs_it():
    m = _mod()
    gh = FakeGitHub([{"number": 1, "body": f"A.\n\n---\n{FOOT}"}, {"number": 2, "body": "B."}],
                    {1: [{"id": 9, "body": f"Looks fine.\n\n{LINK}"}], 2: [{"id": 10, "body": "Fine."}]})
    assert m.run(gh, "workflow_dispatch", {}) == 2
    assert gh.calls == [("PATCH", "pulls/1", {"body": "A.\n"}), ("PUT", "pulls/1/reviews/9", {"body": "Looks fine.\n"})]


def test_pull_request_event_edits_that_description():
    m = _mod()
    gh = FakeGitHub([], {})
    m.run(gh, "pull_request_target", {"pull_request": {"number": 5, "body": f"C.\n{FOOT}"}})
    assert gh.calls == [("PATCH", "pulls/5", {"body": "C.\n"})]
